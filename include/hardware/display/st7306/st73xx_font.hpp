    if (uc == 'P') return &GAME2048_FONT[17 * GAME2048_FONT_HEIGHT];      // P
    if (uc == 'l') return &GAME2048_FONT[18 * GAME2048_FONT_HEIGHT];      // l
    if (uc == 'a') return &GAME2048_FONT[19 * GAME2048_FONT_HEIGHT];      // a
